#!/usr/bin/env bash
#
# Create .env.production with fresh random secrets for a real host.
#
#   ./scripts/gen-env.sh attendly.example.com you@example.com
#   ./scripts/gen-env.sh localhost --local     # HTTPS on :8443, for a smoke test
#
# Secrets are generated as hex on purpose: POSTGRES_PASSWORD is interpolated
# straight into DATABASE_URL, and base64 characters such as + and / would break
# that URL.
set -euo pipefail
cd "$(dirname "$0")/.."

DOMAIN="${1:-}"
MODE="${2:-}"

if [ -z "$DOMAIN" ]; then
  echo "usage: $0 <domain> [acme-email | --local] [--force]" >&2
  exit 1
fi

FORCE=0
for arg in "${3:-}" "${4:-}"; do
  [ "$arg" = "--force" ] && FORCE=1
done
if [ -f .env.production ] && [ "$FORCE" = 0 ]; then
  echo ".env.production already exists. Move it aside first, or pass --force." >&2
  exit 1
fi

rand() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    head -c "$((2 * $1))" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

if [ "$MODE" = "--local" ]; then
  # Caddy issues an internal certificate for localhost, so this needs no DNS and
  # no ACME account. Ports are shifted so a smoke test cannot collide with
  # anything already listening on 80/443.
  ACME_EMAIL="admin@$DOMAIN"
  ORIGIN="https://$DOMAIN:8443"
  HTTP_PORT=8080
  HTTPS_PORT=8443
else
  ACME_EMAIL="${MODE:-admin@$DOMAIN}"
  ORIGIN="https://$DOMAIN"
  HTTP_PORT=80
  HTTPS_PORT=443
fi

umask 077
cat > .env.production <<EOF
# Generated by scripts/gen-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Secrets: keep out of version control, and store a copy somewhere safe.

DOMAIN=$DOMAIN
ACME_EMAIL=$ACME_EMAIL
WEB_ORIGIN=$ORIGIN
HTTP_PORT=$HTTP_PORT
HTTPS_PORT=$HTTPS_PORT

POSTGRES_USER=attendly
POSTGRES_PASSWORD=$(rand 24)
POSTGRES_DB=attendly

CSRF_SECRET=$(rand 32)

COOKIE_SECURE=true
NODE_ENV=production
RELEASE=local

TEACHER_NAME=
TEACHER_EMAIL=
TEACHER_PASSWORD=
EOF

chmod 600 .env.production 2>/dev/null || true
echo "✓ Wrote .env.production for $ORIGIN"
if [ "$MODE" = "--local" ]; then
  echo "  Smoke-test ports: HTTP ${HTTP_PORT}, HTTPS ${HTTPS_PORT} (self-signed certificate)"
else
  echo "  Check that $DOMAIN resolves to this host before the first deploy:"
  echo "    dig +short $DOMAIN"
fi
echo "  Next: add this file to your secret store, then run scripts/deploy.sh"
